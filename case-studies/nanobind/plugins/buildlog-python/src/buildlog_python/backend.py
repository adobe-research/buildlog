"""A PEP 517 build backend that drives buildlog (a prototype).

A frontend (pip, build, cibuildwheel) runs this module in the interpreter
the wheel is for; that choice is the user's, so the backend states it as a
buildlog user decision: a generated user file names sys.executable as the
interpreter and declares one Release configuration for it on the host
platform. The packager's other decisions (the toolchain, rule-package
paths) come in as config settings. buildlog itself runs as an external
tool, as scikit-build-core runs cmake: buildlog needs Python 3.12 or newer,
and the interpreter being built for may be older, so this module uses only
the standard library (3.11+, for tomllib in .wheel).

Config settings (pip wheel -C key=value; repeatable where noted):
  buildlog.command       how to run buildlog (default $BUILDLOG_COMMAND, else
                         "buildlog"), split like a shell command line
  buildlog.user          a user file for configure (repeatable)
  buildlog.package-path  a rule-package prefix (repeatable)
  buildlog.platform      the configuration's platform (default: the host's,
                         e.g. arm64-macos)
  buildlog.ninja         the ninja program (default "ninja")
  build-dir              the build directory (default
                         build/buildlog/<sys.implementation.cache_tag>)
"""

from __future__ import annotations

import os
import platform
import shlex
import subprocess
import sys
from pathlib import Path

from .wheel import build_wheel as assemble_wheel

CONFIG = "pep517"


def _list(value: object) -> list[str]:
    if value is None:
        return []
    return [value] if isinstance(value, str) else [str(v) for v in value]


def _host_platform() -> str:
    if sys.platform == "darwin":
        return f"{platform.machine()}-macos"
    if sys.platform.startswith("linux"):
        return f"{platform.machine().replace('aarch64', 'arm64')}-linux"
    raise RuntimeError("buildlog backend: set -C buildlog.platform=<platform> on this host")


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def user_file(executable: str, plat: str) -> str:
    """The frontend's interpreter choice, as a buildlog user file."""
    return (
        "# Generated by buildlog_python.backend: the interpreter the PEP 517\n"
        "# frontend runs the backend in, and one Release configuration for it.\n"
        f"python_interpreter = [[{_toml_str(CONFIG)}, {_toml_str(executable)}]]\n"
        f"config_decl = [[{_toml_str(CONFIG)}, {_toml_str(plat)}]]\n"
        "config_decl_setting = [\n"
        f'  [{_toml_str(CONFIG)}, "native.opt", "release"],\n'
        f'  [{_toml_str(CONFIG)}, "python.interpreter", {_toml_str(CONFIG)}],\n'
        "]\n"
    )


def build_wheel(wheel_directory, config_settings=None, metadata_directory=None):
    cs = config_settings or {}
    project = Path.cwd()
    builddir = Path(
        cs.get("build-dir") or project / "build" / "buildlog" / sys.implementation.cache_tag
    ).resolve()
    builddir.mkdir(parents=True, exist_ok=True)
    user = builddir / "pep517-user.toml"
    user.write_text(user_file(sys.executable, cs.get("buildlog.platform") or _host_platform()))
    command = shlex.split(
        cs.get("buildlog.command") or os.environ.get("BUILDLOG_COMMAND", "buildlog")
    )
    argv = [*command, "configure"]
    for prefix in _list(cs.get("buildlog.package-path")):
        argv += ["--package-path", prefix]
    for u in _list(cs.get("buildlog.user")):
        argv += ["--user", u]
    argv += ["--user", str(user), "--config", CONFIG, "-C", str(builddir), str(project)]
    subprocess.run(argv, check=True)
    subprocess.run([cs.get("buildlog.ninja", "ninja"), "-C", str(builddir / "souffle")], check=True)
    wheel = assemble_wheel(builddir, CONFIG, project / "pyproject.toml", Path(wheel_directory))
    return wheel.name


def get_requires_for_build_wheel(config_settings=None):
    return []


