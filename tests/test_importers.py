def errors(rows):
    return [row[0] for row in of(rows, "error")]


def target_errors(rows):
    return {(t, msg) for t, msg in of(rows, "target_error")}


def facts(rows):
    """The fact rows, without status, conditions and errors."""
    skip = {"import", "condition", "error", "target_error"}
    return {(k, row) for k, row in rows if k not in skip}


