    (first / "libsample.a").write_bytes(b"earlier directory wins")
    assert not certificate.valid()
    rows, _ = available_import("pc", file)
    assert rows["av_pkg_link"] == [("bundle", "pc:sample", str(first / "libsample.a"), "")]


