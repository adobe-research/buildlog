def imp(fmt, path, results=RESULTS):
    """Rows of one import (request id dropped) and their origins."""
    out = importers.pkg_import(None, "r", (fmt, str(path)), results)
    rows = set()
    for rel, values in out.items():
        if rel != "__origin__":
            rows |= {(rel.removeprefix("res_pkg_"), row[1:]) for row in values}
    origins = {(rel.removeprefix("res_pkg_"), row[1:]): o for rel, row, o in out["__origin__"]}
    return rows, origins


def of(rows, kind):
    return {row for k, row in rows if k == kind}


def available_import(fmt, path, *, sysroot="", namespace=""):
    certificate = Certificate()
    rows = decode_file(
        importers.PROVIDERS[fmt],
        "bundle",
        path,
        namespace,
        Vocabulary(frozenset({"macos", "linux"}), frozenset({"arm64", "x86_64"})),
        certificate,
        sysroot,
    )
    certificate.confirm()
    return rows, certificate


