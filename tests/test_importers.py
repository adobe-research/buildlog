def test_cps_attributes_platform_and_configuration_overrides():
    rows, origins = imp("cps", FIX / "cps" / "Multi" / "Multi.cps")
    plat = "(platform.cpu=arm64 & platform.os=macos)"
    on, dbg = f"import:{plat}", f"import:({plat} & native.package_config=debug)"
    not_dbg, not_rel = (
        f"import:({plat} & !native.package_config=debug)",
        f"import:({plat} & !native.package_config=release)",
    )
    core = "Multi:core"
    assert facts(rows) == {
        ("target", (core, "library")),
        ("target", ("Multi:base", "interface")),
        ("target", ("Multi:tool", "executable")),
        ("package", (core, "Multi", "core")),
        ("package", ("Multi:base", "Multi", "base")),
        ("package", ("Multi:tool", "Multi", "tool")),
        ("dep", (core, "Multi:base", "public", on)),
        ("dep", (core, "Other:thing", "public", on)),
        ("dep", (core, "Hidden:*", "private", on)),
        # includes: "*" and "cpp" apply, "c" does not; Release unsets them
        ("prop", (core, "cc.include_dir", "/opt/multi/include", not_rel)),
        ("prop", (core, "cc.include_dir", "/opt/multi/include/c++", not_rel)),
        # Debug's definitions replace the component's
        ("prop", (core, "cc.define", "MULTI=1", not_dbg)),
        ("prop", (core, "cc.define", "MULTI_BARE", not_dbg)),
        ("prop", (core, "cc.define", "MULTI_DEBUG=1", dbg)),
        ("prop", (core, "cc.compile_flag", "-fno-rtti", on)),
        ("prop", (core, "cxx.std", "20", on)),
        ("prop", (core, "cc.compile_flag", "-pthread", on)),
        ("prop", (core, "native.link_flag", "-pthread", on)),
        ("prop", (core, "native.link_flag", "-Wl,-x", on)),
        ("prop", (core, "native.link_flag", "-lz", on)),
        ("prop", (core, "native.link_flag", "-framework Foundation", on)),
        ("link", (core, "/usr/lib/libobjc.A.tbd", on)),
        # RelWithDebInfo maps to no buildlog setting: its location is dropped
        ("location", (core, "/opt/multi/lib/libcore.a", not_dbg)),
        ("location", (core, "/opt/multi/lib/libcored.a", dbg)),
        # a relative path is relative to the CPS file
        ("location", ("Multi:tool", str(FIX / "cps" / "Multi" / "bin" / "multi-tool"), on)),
    }
    assert target_errors(rows) == {
        (
            "Multi:base",
            (
                f"{FIX / 'cps' / 'Multi' / 'Multi.cps'}:25: Multi:base: "
                "compile feature 'c_std_99' has no buildlog mapping"
            ),
        )
    }
    assert ("condition", (dbg, f"$And({RENDER_PLAT}, $Eq(native.package_config, debug))")) in rows
    multi = FIX / "cps" / "Multi" / "Multi.cps"
    debug_line = line_of(multi, '"Debug": {"location"')
    assert origins[("prop", (core, "cc.define", "MULTI_DEBUG=1", dbg))] == f"{multi}:{debug_line}"


