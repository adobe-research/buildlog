    project = bare_consumer(tmp_path, [(BARE_HUM, "Hum"), (BARE_ECHO, "Echo")])
    build = tmp_path / "build"
    facts_dir, metrics = configure_project(
        project, build, update_lock=True, user_files=[project / "user.toml"]
    )
    assert metrics["errors"] == []
    resolves = (facts_dir / "dep_resolves.csv").read_text().splitlines()
    assert "Echo::echo\tHum::hum\tHum::hum" in resolves
    ninja = (build / "souffle" / "build.ninja").read_text()
    assert "-DHUM=1" in ninja
    assert f"{PREFIX}/lib/libecho.a" in ninja and f"{PREFIX}/lib/libhum.a" in ninja


