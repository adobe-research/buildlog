def greet_facts(ns, prefix, *, tool=True, sep="::"):
    """Greet's facts; CMake ids are `ns::name`, CPS ids `ns:name`."""
    lib = f"{prefix}/lib"
    out = {
        ("target", (f"{ns}{sep}greet", "library")),
        ("target", (f"{ns}{sep}shout", "library")),
        ("target", (f"{ns}{sep}greet_detail", "interface")),
        ("dep", (f"{ns}{sep}greet", f"{ns}{sep}greet_detail", "private", "")),
        ("dep", (f"{ns}{sep}shout", f"{ns}{sep}greet", "public", "")),
        ("prop", (f"{ns}{sep}greet_detail", "cc.define", "GREET_DETAIL=1", "")),
        ("prop", (f"{ns}{sep}greet", "cc.include_dir", f"{prefix}/include", "")),
        ("prop", (f"{ns}{sep}greet", "cc.define", "GREET_API=1", "")),
        ("prop", (f"{ns}{sep}greet", "cxx.std", "17", "")),
        ("location", (f"{ns}{sep}greet", f"{lib}/libgreetd.a", DEBUG)),
        ("location", (f"{ns}{sep}greet", f"{lib}/libgreet.a", RELEASE)),
        ("location", (f"{ns}{sep}shout", f"{lib}/libshoutd.1.2.3.dylib", DEBUG)),
        ("location", (f"{ns}{sep}shout", f"{lib}/libshout.1.2.3.dylib", RELEASE)),
    }
    if tool:
        out |= {
            ("target", (f"{ns}{sep}greet-tool", "executable")),
            ("location", (f"{ns}{sep}greet-tool", f"{prefix}/bin/greet-tool", DEBUG)),
            ("location", (f"{ns}{sep}greet-tool", f"{prefix}/bin/greet-tool", RELEASE)),
        }
    return out


def test_cps_generated_package_merges_configurations():
    rows, origins = imp("cps", GREET_CPS)
    assert of(rows, "import") == {("ok",)}
    # CPS ids are the CPS spellings Pkg:comp, not CMake's Pkg::comp, and the
    # importer states no equivalence between them
    assert facts(rows) == greet_facts("Greet", str(PREFIX), sep=":") | {
        # Pkg:* is the package's default components
        ("target", ("Greet:*", "interface")),
        ("dep", ("Greet:*", "Greet:greet", "public", "")),
        # the package name means its default components (CPS's own rule)
        ("alias", ("Greet", "Greet:*")),
        # each target's package, by the package's own name, and its version
        ("package", ("Greet:*", "Greet", "")),
        *{
            (kind, row)
            for c in ("greet", "shout", "greet_detail", "greet-tool")
            for kind, row in [
                ("package", (f"Greet:{c}", "Greet", c)),
                ("version", (f"Greet:{c}", "1", "2", "3")),
            ]
        },
        ("version", ("Greet:*", "1", "2", "3")),
    }
    loc = ("location", ("Greet:greet", f"{PREFIX}/lib/libgreetd.a", DEBUG))
    assert origins[loc].startswith(f"{GREET_CPS.parent / 'Greet@debug.cps'}:")


