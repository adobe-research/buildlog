def write_cps(tmp_path, doc, name="Pkg"):
    path = tmp_path / name / f"{name}.cps"
    path.parent.mkdir(parents=True, exist_ok=True)
    base = {"cps_version": "0.14.1", "name": name, "components": {}}
    path.write_text(json.dumps(base | doc, indent=1) if isinstance(doc, dict) else doc)
    return path


