def test_cmake_rpath_of_a_sysroot_library_is_its_path_on_the_target(tmp_path):
    """A library under the target's sysroot is found at run time at its path on
    the target, not on the machine that links it."""
    sysroot = tmp_path / "sysroot"
    elf = sysroot / "opt" / "cfg"
    shutil.copytree(CMAKE_DIR / "GreetAbs", elf)
    for f in elf.glob("*.cmake"):
        f.write_text(
            f.read_text()
            .replace("libshout.1.2.3.dylib", "libshout.so.1.2.3")
            .replace("@rpath/libshout.1.dylib", "libshout.so.1")
            .replace("libshoutd.1.2.3.dylib", "libshoutd.so.1.2.3")
            .replace("@rpath/libshoutd.1.dylib", "libshoutd.so.1")
            .replace("/opt/greet", f"{sysroot}/opt/greet")
        )
    target = elf / "GreetAbs-targets.cmake"

    def rpaths(*root):
        out = importers.pkg_import(None, "r", ("cmake", str(target), "", *root), RESULTS)
        return {row[3] for row in out["res_pkg_prop"] if row[2] == "native.link_flag"}

    assert rpaths("") == {f"-Wl,-rpath,{sysroot}/opt/greet/lib"}
    assert rpaths(str(sysroot)) == {"-Wl,-rpath,/opt/greet/lib"}


def test_pc_paths_of_a_sysroot_file_are_under_the_sysroot(tmp_path):
    """pkg-config's PKG_CONFIG_SYSROOT_DIR: absolute -I and -L of a target's .pc
    name files in the sysroot, and -l resolves there; a path already under it
    stays."""
    sysroot = tmp_path / "sysroot"
    (sysroot / "usr" / "lib").mkdir(parents=True)
    (sysroot / "usr" / "include").mkdir(parents=True)
    (sysroot / "usr" / "lib" / "libfoo.so").write_text("")
    pc = sysroot / "usr" / "lib" / "pkgconfig" / "foo.pc"
    pc.parent.mkdir()
    pc.write_text(
        "Name: foo\nVersion: 1\nDescription: x\n"
        f"Cflags: -I/usr/include/foo -isystem /usr/include -I{sysroot}/usr/include/bar\n"
        "Libs: -L/usr/lib -lfoo\n"
    )

    def facts_of(root):
        out = importers.pkg_import(None, "r", ("pc", str(pc), "", root), RESULTS)
        props = {(row[2], row[3]) for row in out["res_pkg_prop"]}
        return props, {row[2] for row in out["res_pkg_link"]}

    props, links = facts_of(str(sysroot))
    assert props == {
        ("cc.include_dir", f"{sysroot}/usr/{d}") for d in ("include/foo", "include", "include/bar")
    }
    assert links == {f"{sysroot}/usr/lib/libfoo.so"}
    props, links = facts_of("")
    assert ("cc.include_dir", "/usr/include/foo") in props
    assert links == set() or all(not x.startswith(str(sysroot)) for x in links)
