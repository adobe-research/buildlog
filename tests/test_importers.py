def test_pc_variables_fields_and_link_resolution():
    rows, origins = imp("pc", FIX / "pc" / "alpha.pc")
    pc = str(FIX / "pc")
    assert of(rows, "import") == {("ok",)}
    assert facts(rows) == {
        ("target", ("pc:alpha", "interface")),
        # The file names its module, the binding of the bare name; Provides
        # states other names (as bare names and as pkg-config ids)
        ("alias", ("alpha", "pc:alpha")),
        ("alias", ("alpha-compat", "pc:alpha")),
        ("alias", ("pc:alpha-compat", "pc:alpha")),
        # the module is its own package, at its Version
        ("package", ("pc:alpha", "alpha", "")),
        ("version", ("pc:alpha", "1", "0", "0")),
        # Requires and Requires.private are edges to pkg-config ids, constraints
        # ignored
        ("dep", ("pc:alpha", "pc:beta", "public", "")),
        ("dep", ("pc:alpha", "pc:gamma", "public", "")),
        ("dep", ("pc:alpha", "pc:delta", "public", "")),
        ("prop", ("pc:alpha", "cc.include_dir", f"{pc}/include/alpha", "")),
        ("prop", ("pc:alpha", "cc.include_dir", f"{pc}/include/sys", "")),
        ("prop", ("pc:alpha", "cc.define", "ALPHA=1", "")),
        ("prop", ("pc:alpha", "cc.define", "ALPHA_FLAVOR=plain", "")),
        ("prop", ("pc:alpha", "cc.compile_flag", "-pthread", "")),
        # -l resolved against the file's -L directories is a link file ...
        ("link", ("pc:alpha", f"{pc}/lib/libalpha.a", "")),
        ("link", ("pc:alpha", f"{pc}/lib/libextra.a", "")),
        # ... an unresolved one (system library) stays a flag; -L never does
        ("prop", ("pc:alpha", "native.link_flag", "-lmissing", "")),
        ("prop", ("pc:alpha", "native.link_flag", "-lm", "")),
        ("prop", ("pc:alpha", "native.link_flag", "-framework CoreFoundation", "")),
        ("prop", ("pc:alpha", "native.link_flag", "-Wl,-dead_strip", "")),
    }
    assert origins[("prop", ("pc:alpha", "cc.define", "ALPHA=1", ""))] == f"{pc}/alpha.pc:14"
    assert origins[("link", ("pc:alpha", f"{pc}/lib/libalpha.a", ""))] == f"{pc}/alpha.pc:15"
    assert origins[("dep", ("pc:alpha", "pc:delta", "public", ""))] == f"{pc}/alpha.pc:13"
    assert origins[("alias", ("pc:alpha-compat", "pc:alpha"))] == f"{pc}/alpha.pc:17"
    assert origins[("alias", ("alpha", "pc:alpha"))] == f"{pc}/alpha.pc:1"


