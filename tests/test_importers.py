def test_available_pc_records_ordered_negative_library_lookups(tmp_path):
    first, second = tmp_path / "first", tmp_path / "second"
    first.mkdir()
    second.mkdir()
    (second / "libsample.so").write_bytes(b"later")
    file = tmp_path / "sample.pc"
    file.write_text(f"Name: sample\nLibs: -L{first} -L{second} -lsample\n")
    rows, certificate = available_import("pc", file)
    assert rows["av_pkg_link"] == [("bundle", "pc:sample", str(second / "libsample.so"), "")]
    # Contents are checked by artifact probes, not metadata lookup.
    (second / "libsample.so").write_bytes(b"replacement")
